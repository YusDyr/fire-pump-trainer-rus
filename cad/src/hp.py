# Ступень высокого давления по рис. 5 РЭ насоса (разрез А-А) и её положение по рис. 1.
# Масштаб рис. 5: 3,9 пикс/мм по подшипникам 308 (D 90, d 40, B 23) и 304 (D 52, d 20, B 15); ось вала на скане y=736.
# Положение: ось ВД параллельна оси НД, смещена на y=-198, z=+55 мм (вид слева рис. 1: ступень 17 слева вверху),
# торец корпуса 14 — у задней стенки улитки НД, x≈318 мм (вид справа рис. 1).
# Промежуточное колесо 23 — между осями ВД и НД, на линии их центров (линия А-А на рис. 5 наклонена так же).
import math, Part
from FreeCAD import Vector as V

SH = 3.9; AXH = 736
Y0, Z0 = -198.0, 55.0
XR = 318.0                       # глобальный x торца корпуса 14 (px 1515)
def XG(px): return XR + (px - 1515) / SH
U_ND = V(0, 198.0, -55.0); U_ND.normalize()   # от оси ВД к оси НД (в плоскости YZ)

def rev(poly):
    pts = [V(XG(x), r, 0) for x, r in poly]
    f = Part.Face(Part.makePolygon(pts + [pts[0]])); f.rotate(V(0,0,0), V(1,0,0), 90)
    s = f.revolve(V(0,0,0), V(1,0,0), 360); s.translate(V(0, Y0, Z0)); return s

def cyl(r, p, d, h): return Part.makeCylinder(r, h, p, d)
def ax(px, off=V(0,0,0)): return V(XG(px), Y0, Z0) + off

PARTS = []   # (name, label, shape, color)
def add(n, l, s, c): PARTS.append((n, l, s, c))

def build():
    steel = (0.78,0.79,0.82); cast = (0.5,0.56,0.62); brg = (0.22,0.23,0.27); bronze = (0.8,0.63,0.33)
    add('VD_val_4', 'ВД 4 Вал-шестерня (полый: охлаждение водой)',
        rev([(200,7.5),(200,20),(308,20),(308,17.7),(600,17.7),(600,24),(700,24),(700,20),(800,20),(800,22),(1000,22),(1000,17.5),(1390,17.5),(1390,7.5)]), steel)
    add('VD_podshipnik_308_lev', 'ВД 1 Подшипник 308', rev([(217,20),(217,45),(308,45),(308,20)]), brg)
    add('VD_podshipnik_308_prav', 'ВД 1 Подшипник 308', rev([(712,20),(712,45),(800,45),(800,20)]), brg)
    tube = rev([(205,45),(205,55),(560,55),(560,58),(840,58),(840,75),(880,75),(880,48.5),(800,48.5),(800,45),(712,45),(712,48.5),(308,48.5),(308,45)])
    # корпус шестерни 23 — прилив в сторону оси НД
    gp = ax(580, U_ND * 82)
    case = cyl(72, gp, V(1,0,0), XG(770) - XG(580)).cut(cyl(66, gp + V(3,0,0), V(1,0,0), XG(770) - XG(580) - 6))
    tube = tube.cut(cyl(65, gp + V(3,0,0), V(1,0,0), XG(770) - XG(580) - 6)).fuse(case).cut(cyl(48.5, ax(560), V(1,0,0), XG(712) - XG(560)))
    add('VD_korpus_5', 'ВД 5 Корпус опор и шестерни', tube.removeSplitter(), cast)
    add('VD_kryshka_30', 'ВД 30 Крышка (камера подвода охлаждающей воды)', rev([(125,0),(125,50),(217,50),(217,40),(145,40),(145,0)]), cast)
    add('VD_shtucer', 'ВД Штуцер подвода воды к полому валу', cyl(7, ax(175, V(0,0,48)), V(0,0,1), 30), (0.8,0.65,0.3))
    add('VD_salnik_21', 'ВД 21 Сальниковое уплотнение вала', rev([(860,22),(860,32.6),(1000,32.6),(1000,22)]), (0.12,0.12,0.12))
    k14 = rev([(880,48.5),(880,100),(998,100),(998,140),(1062,140),(1062,128),(1470,128),(1515,105),(1515,30),(1490,30),(1490,110),(1062,110),(1062,64),(1000,64),(1000,32.6),(880,32.6)])
    k14 = k14.cut(rev([(905,36),(905,64),(1000,64),(1000,36)]))   # камера подвода (вход ступени ВД)
    # приливы сверху: вход от коллектора НД (патрубок 29) и выход в коллектор ВД 22
    for x0, x1, nm in ((800, 1100, 'вход'), (1180, 1490, 'выход')):
        b = Part.makeBox(XG(x1) - XG(x0), 80, 40, V(XG(x0), Y0 - 40, Z0 + 118)).fuse(
            Part.makeBox(XG(x1) - XG(x0) + 20, 110, 12, V(XG(x0) - 10, Y0 - 55, Z0 + 158)))
        b = b.cut(cyl(16, V((XG(x0) + XG(x1)) / 2, Y0, Z0 + 60), V(0,0,1), 120))
        k14 = k14.fuse(b)
    # приливы кранов слива ВД 32, 33 снизу
    for px in (1150, 1300):
        k14 = k14.fuse(cyl(11, ax(px, V(0,0,-120)), V(0,0,-1), 25)).cut(cyl(5, ax(px, V(0,0,-100)), V(0,0,-1), 50))
    add('VD_korpus_14', 'ВД 14 Корпус ступени (с приливами входа и выхода)', k14.removeSplitter(), cast)
    add('VD_koleso_18', 'ВД 18 Колесо рабочее 1-й ступени', rev([(1060,17.5),(1060,48),(1095,50),(1110,85),(1135,85),(1150,40),(1155,17.5)]), bronze)
    add('VD_koleso_16', 'ВД 16 Колесо рабочее 2-й ступени (встречное)', rev([(1215,17.5),(1220,40),(1235,85),(1260,85),(1275,50),(1305,48),(1305,17.5)]), bronze)
    add('VD_apparat_17', 'ВД 17 Аппарат направляющий', rev([(1155,30),(1155,90),(1095,90),(1095,108),(1290,108),(1290,90),(1215,90),(1215,30)]), (0.62,0.66,0.7))
    add('VD_apparat_15', 'ВД 15 Аппарат направляющий', rev([(1305,45),(1305,108),(1350,108),(1350,45)]), (0.62,0.66,0.7))
    add('VD_gayka', 'ВД Гайка конца вала', rev([(1390,7.5),(1390,20),(1420,20),(1420,7.5)]), (0.45,0.47,0.5))
    g = ax(605, U_ND * 82)
    gear = cyl(63, g, V(1,0,0), XG(701) - XG(605)).cut(cyl(26, g - V(1,0,0), V(1,0,0), 40))
    teeth = []
    for i in range(48):  # условные зубья
        a = 2 * math.pi * i / 48
        d = V(0, math.cos(a), math.sin(a))
        teeth.append(cyl(2.2, g + d * 63, V(1,0,0), XG(701) - XG(605)))
    for t in teeth: gear = gear.cut(t)
    add('VD_koleso_23', 'ВД 23 Колесо зубчатое промежуточное', gear, (0.72,0.5,0.25))
    pin = cyl(22, ax(600), V(1,0,0), XG(700) - XG(600)).cut(cyl(17.7, ax(599), V(1,0,0), 60))
    for i in range(18):
        a = 2 * math.pi * i / 18; d = V(0, math.cos(a), math.sin(a))
        pin = pin.fuse(cyl(2.3, ax(600) + d * 23, V(1,0,0), XG(700) - XG(600)))
    add('VD_shesternya_vala', 'ВД Зубчатый венец вала-шестерни 4', pin, (0.72,0.5,0.25))
    add('VD_os_25', 'ВД 25 Ось', cyl(10, ax(530, U_ND * 82), V(1,0,0), XG(797) - XG(530)), steel)
    add('VD_podshipniki_304', 'ВД 24 Подшипники 304 (2 шт.)', cyl(26, ax(597, U_ND * 82), V(1,0,0), XG(722) - XG(597)).cut(cyl(10, ax(590, U_ND * 82), V(1,0,0), 40)), brg)
    # кронштейн крепления к корпусу НД (наклонный фланец на рис. 5)
    p = ax(700, U_ND * 112)
    br = Part.makeBox(XG(1000) - XG(700), 40, 120, V(0, -20, -60))
    br.rotate(V(0,0,0), V(1,0,0), math.degrees(math.atan2(-55, 198)))
    br.translate(p)
    add('VD_kronshteyn', 'ВД Кронштейн крепления к корпусу НД (условно)', br, cast)
    return PARTS
